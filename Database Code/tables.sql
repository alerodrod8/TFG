CREATE DATABASE IF NOT EXISTS USDATABASE;
USE USDATABASE;

DROP TABLE IF EXISTS checkins;
DROP TABLE IF EXISTS administrators;
DROP TABLE IF EXISTS workers;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS hq;
DROP TABLE IF EXISTS states;
DROP TABLE IF EXISTS jobpositions;
DROP TABLE IF EXISTS statuses;

CREATE TABLE IF NOT EXISTS STATUSES(
	id INT NOT NULL AUTO_INCREMENT,
	status_description VARCHAR(128) NOT NULL,
	PRIMARY KEY (id),
	UNIQUE (status_description)
);

CREATE TABLE IF NOT EXISTS JOBPOSITIONS(
	id INT NOT NULL AUTO_INCREMENT,
	jobpos_name VARCHAR(256) NOT NULL,
	abbreviation VARCHAR(32) NOT NULL,
	PRIMARY KEY (id),
	UNIQUE (jobpos_name)
);

CREATE TABLE IF NOT EXISTS STATES(
	id INT NOT NULL AUTO_INCREMENT,
	state_name VARCHAR(128) NOT NULL,
	abbreviation VARCHAR(32) NOT NULL,
	PRIMARY KEY (id),
	UNIQUE (state_name),
	UNIQUE (abbreviation)
);

CREATE TABLE IF NOT EXISTS HQ(
	id INT NOT NULL AUTO_INCREMENT,
	hq_name VARCHAR(128) NOT NULL,
	state VARCHAR(32) NOT NULL,
	city VARCHAR(128) NOT NULL,
	location VARCHAR(128) NOT NULL,
	postCode INT NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY (state) REFERENCES STATES(abbreviation)
);

CREATE TABLE IF NOT EXISTS DEPARTMENTS(
	id INT NOT NULL AUTO_INCREMENT,
	department_name VARCHAR(256) NOT NULL,
	abbreviation VARCHAR(32) NOT NULL,
	associated_hq INT,
	PRIMARY KEY (id),
	FOREIGN KEY (associated_hq) REFERENCES hq(id),
	UNIQUE (department_name)
);

CREATE TABLE IF NOT EXISTS WORKERS(
	id INT NOT NULL AUTO_INCREMENT,
	state_id INT NOT NULL,
	hq_id INT NOT NULL,
	department_id INT NOT NULL,
	username VARCHAR(128) NOT NULL,
	username2 VARCHAR(128),
	surname VARCHAR(128) NOT NULL,
	surname2 VARCHAR(128),
	surname3 VARCHAR(128),
	jobpos_id INT NOT NULL,
	bdate DATE,
	email VARCHAR(128),
	worker_status VARCHAR(128) NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY (state_id) REFERENCES STATES(id),
	FOREIGN KEY (hq_id) REFERENCES HQ(id),
	FOREIGN KEY (department_id) REFERENCES DEPARTMENTS(id),
	FOREIGN KEY (jobpos_id) REFERENCES JOBPOSITIONS(id),
	FOREIGN KEY (worker_status) REFERENCES STATUSES(status_description),
	UNIQUE (email)
);
	
CREATE TABLE IF NOT EXISTS ADMINISTRATORS(
	id INT NOT NULL AUTO_INCREMENT,
	state_id INT NOT NULL,
	hq_id INT NOT NULL,
	department_id INT NOT NULL,
	username VARCHAR(128) NOT NULL,
	username2 VARCHAR(128),
	surname VARCHAR(128) NOT NULL,
	surname2 VARCHAR(128),
	surname3 VARCHAR(128),
	jobpos_id INT NOT NULL,
	bdate DATE,
	email VARCHAR(128),
	admin_status VARCHAR(128) NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY (state_id) REFERENCES STATES(id),
	FOREIGN KEY (hq_id) REFERENCES HQ(id),
	FOREIGN KEY (department_id) REFERENCES DEPARTMENTS(id),
	FOREIGN KEY (jobpos_id) REFERENCES JOBPOSITIONS(id),
	FOREIGN KEY (admin_status) REFERENCES STATUSES(status_description),
	UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS CHECKINS(
	id INT NOT NULL AUTO_INCREMENT,
	workerid INT NULL,
	adminid INT NULL,
	checktime DATETIME NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY (workerid) REFERENCES workers(id),
	FOREIGN KEY (adminid) REFERENCES administrators(id)
);